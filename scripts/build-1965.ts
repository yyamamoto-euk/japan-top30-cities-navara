// --- 表の形を確かめる ---
if (TABLE.length !== EXPECTED_ROWS) throw new Error(`表の行が ${TABLE.length}（${EXPECTED_ROWS} のはず）`);
for (let i = 1; i < TABLE.length; i++)
  if (TABLE[i][1] > TABLE[i - 1][1]) throw new Error(`並びが人口の多い順になっていない：${TABLE[i - 1][0]} ${TABLE[i - 1][1]} → ${TABLE[i][0]} ${TABLE[i][1]}`);
if (new Set(TABLE.map(([n]) => n)).size !== TABLE.length) throw new Error("同じ名前が2回出てくる");
if (TABLE.some(([, p]) => p < 100000)) throw new Error("10万人未満の行がある");
const rankOf = new Map(TABLE.map(([n], i) => [n, i + 1]));
const popOf = new Map(TABLE);

// --- 足す行を決める ---
const entities = loadEntities();
type Add = { name: string; pref: string; pop: number; rank: number; why: string; entity: string };
const add = new Map<string, Add>();
const noValue: string[] = [];
for (const e of entities) {
  if (e.merged_into && e.merged_year !== null && e.merged_year <= 1965) continue;
  const name = e.names.find((n) => popOf.has(n));
  if (!name) {
    noValue.push(`${e.entity_id}（${e.names.join("・")}）`);
    continue;
  }
  const rank = rankOf.get(name)!;
  add.set(name, { name, pref: e.pref_now, pop: popOf.get(name)!, rank, why: rank <= TOP ? `上位${TOP}・柱` : "柱", entity: e.entity_id });
}
// 上位40はすべて柱に当たるはず（当たらない市は都道府県が分からないので止める）
const topNoEntity = TABLE.slice(0, TOP).filter(([n]) => !add.has(n)).map(([n]) => n);
if (topNoEntity.length) throw new Error(`上位${TOP}で柱に当たらない市：${topNoEntity.join("、")}。entities.csv に足してから実行する`);
const adds = [...add.values()].sort((a, b) => a.rank - b.rank);

// --- observations.csv に書く ---
const rows = readCsv(PATHS.observations);
const header = Object.keys(rows[0]);
const kept = rows.filter((r) => r.source_id !== SOURCE_ID);
const removed = rows.length - kept.length;
for (const a of adds) {
  const v: Record<string, string> = {
    year: "1965",
    rank: String(a.rank),
    name_then: a.name,
    pref_now: a.pref,
    pop: String(a.pop),
    source_id: SOURCE_ID,
    status: "要照合",
    note: `昭和40年国勢調査報告 第15表（65_t_cities100k.pdf）の昭和40年の列を画像から読んだ（${READ_ON}）。1965年10月1日。rankは第15表の並び順（10万人以上の市と東京都区部 ${EXPECTED_ROWS} の中での順位）${READ_NOTES[a.name] ? `。${READ_NOTES[a.name]}` : ""}`,
  };
  kept.push(Object.fromEntries(header.map((h) => [h, v[h] ?? ""])));
}
writeCsv(PATHS.observations, header, kept);

