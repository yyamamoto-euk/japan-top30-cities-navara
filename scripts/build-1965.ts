  大牟田市: "百の位の印字がかすれて 6 とも 8 とも見える。同じ調査の第17表（市区町村別人口、65_t_municipalities_000007917098.pdf p.11）では 193,875 とはっきり読めた。表の並び（山形市 193,737 より上）とも合う",
